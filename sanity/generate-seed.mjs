// Function to generate timestamped chapters and chunks for a video
function generateVideoIntelligence(videoUrl, videoId, lessonTitle, lessonSummary, keyPoints, notesText) {
  const chapters = [
    { _key: 'ch1', startSeconds: 0, label: `Introduction to ${lessonTitle}` },
    { _key: 'ch2', startSeconds: 180, label: `${keyPoints[0] || 'Core Architecture Concepts'}` },
    { _key: 'ch3', startSeconds: 420, label: `${keyPoints[1] || 'Implementation & Code Walkthrough'}` },
    { _key: 'ch4', startSeconds: 720, label: `${keyPoints[2] || 'Best Practices & Edge Cases'}` },
    { _key: 'ch5', startSeconds: 960, label: 'Summary & Production Takeaways' },
  ]

  const chunks = [
    {
      _key: 'c1',
      startSeconds: 10,
      text: `Welcome to this comprehensive lesson on ${lessonTitle}. ${lessonSummary}`,
    },
    {
      _key: 'c2',
      startSeconds: 190,
      text: `Let's dive into ${keyPoints[0] || 'the core foundations'}. ${notesText}`,
    },
    {
      _key: 'c3',
      startSeconds: 435,
      text: `Next, examining ${keyPoints[1] || 'practical execution patterns'}. Writing clean, maintainable, and type-safe code that scales in production environments.`,
    },
    {
      _key: 'c4',
      startSeconds: 735,
      text: `When implementing ${keyPoints[2] || 'advanced configurations'}, you need to account for performance boundaries, error resilience, and edge case conditions.`,
    },
    {
      _key: 'c5',
      startSeconds: 975,
      text: `To wrap up ${lessonTitle}: remember to follow the recommended guidelines and test thoroughly in your CI pipeline.`,
    },
  ]

  return {
    _id: `video-${videoId}`,
    _type: 'video',
    videoId,
    url: videoUrl,
    chapters,
    chunks,
  }
}

// Generate complete data structures
function generateAll() {
  console.log('⚡ Generating 10 courses, 120 unique lessons, and video intelligence documents...')

  const allDocuments = []
  const allVideos = []
  const usedVideoIds = new Set()
  const usedSlugs = new Set()

  // 1. Add categories
  for (const cat of categories) {
    allDocuments.push(cat)
  }

  // 2. Add instructors
  for (const inst of instructors) {
    allDocuments.push(inst)
  }

  let totalLessonCount = 0

  // 3. Process each course
  for (const courseConf of coursesConfig) {
    const courseCoverUrl = `https://picsum.photos/seed/${courseConf.id}/1280/720`
    const courseModules = []

    for (let mIdx = 0; mIdx < courseConf.modules.length; mIdx++) {
      const mod = courseConf.modules[mIdx]
      const moduleLessonRefs = []

      for (let lIdx = 0; lIdx < mod.lessons.length; lIdx++) {
        const les = mod.lessons[lIdx]
        const lessonId = `lesson-${courseConf.id.replace('course-', '')}-${les.num}`
        const videoUrl = `https://www.youtube.com/watch?v=${les.videoId}`
        const thumbnailUrl = `https://picsum.photos/seed/${lessonId}/640/360`

        if (usedVideoIds.has(les.videoId)) {
          console.error(`❌ Duplicate videoId detected: ${les.videoId} in ${lessonId}`)
        }
        usedVideoIds.add(les.videoId)

        if (usedSlugs.has(les.slug)) {
          console.error(`❌ Duplicate slug detected: ${les.slug} in ${lessonId}`)
        }
        usedSlugs.add(les.slug)

        const lessonDoc = {
          _id: lessonId,
          _type: 'lesson',
          title: les.title,
          slug: { _type: 'slug', current: les.slug },
          videoUrl,
          thumbnailUrl,
          duration: les.duration,
          isFreePreview: les.isFreePreview,
          studentCount: les.studentCount,
          summary: les.summary,
          keyPoints: les.keyPoints,
          proTip: les.proTip,
          resources: [
            {
              _key: `r_${lessonId}`,
              title: les.resource.title,
              type: les.resource.type,
              description: les.resource.description,
              url: les.resource.url,
              fileFormat: les.resource.fileFormat,
              fileSize: les.resource.fileSize,
            },
          ],
          content: [
            {
              _type: 'block',
              _key: `b_${lessonId}`,
              style: 'normal',
              markDefs: [],
              children: [
                {
                  _type: 'span',
                  _key: `s_${lessonId}`,
                  text: les.notes,
                },
              ],
            },
          ],
        }

        allDocuments.push(lessonDoc)
        moduleLessonRefs.push({
          _type: 'reference',
          _ref: lessonId,
          _key: `ref_${lessonId}`,
        })
        totalLessonCount++

        // Generate video document
        const videoDoc = generateVideoIntelligence(
          videoUrl,
          les.videoId,
          les.title,
          les.summary,
          les.keyPoints,
          les.notes
        )
        allVideos.push(videoDoc)
        allDocuments.push(videoDoc)
      }

      courseModules.push({
        _key: mod.key,
        title: mod.title,
        summary: mod.summary,
        lessons: moduleLessonRefs,
      })
    }

    const courseDoc = {
      _id: courseConf.id,
      _type: 'course',
      title: courseConf.title,
      slug: { _type: 'slug', current: courseConf.slug },
      description: courseConf.description,
      coverImageUrl: courseCoverUrl,
      level: courseConf.level,
      price: courseConf.price,
      duration: courseConf.duration,
      isPopular: courseConf.isPopular,
      studentCount: courseConf.studentCount,
      iconIdentifier: courseConf.iconIdentifier,
      category: {
        _type: 'reference',
        _ref: courseConf.categoryRef,
      },
      instructor: {
        _type: 'reference',
        _ref: courseConf.instructorRef,
      },
      learningOutcomes: courseConf.learningOutcomes,
      modules: courseModules,
      overview: courseConf.overview,
    }

    allDocuments.push(courseDoc)
  }

  console.log(`✅ Total courses generated: ${coursesConfig.length}`)
  console.log(`✅ Total lessons generated: ${totalLessonCount}`)
  console.log(`✅ Total unique YouTube videos: ${usedVideoIds.size}`)
  console.log(`✅ Total documents in seed: ${allDocuments.length}`)

  // Write sanity/seed-data.ndjson
  const ndjsonContent = allDocuments.map((doc) => JSON.stringify(doc)).join('\n') + '\n'
  fs.writeFileSync(path.resolve(__dirname, 'seed-data.ndjson'), ndjsonContent, 'utf8')
  console.log('📁 Wrote sanity/seed-data.ndjson')

  // Write sanity/videos.json
  fs.writeFileSync(path.resolve(__dirname, 'videos.json'), JSON.stringify(allVideos, null, 2), 'utf8')
  console.log('📁 Wrote sanity/videos.json')

  // Write sanity/videos.ndjson
  const videosNdjson = allVideos.map((v) => JSON.stringify(v)).join('\n') + '\n'
  fs.writeFileSync(path.resolve(__dirname, 'videos.ndjson'), videosNdjson, 'utf8')
  console.log('📁 Wrote sanity/videos.ndjson')
}

generateAll()
